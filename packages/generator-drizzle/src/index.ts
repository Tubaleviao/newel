import type {
  Generator,
  GeneratorContext,
  GeneratorOutput,
  FabricSchema,
  EntitySchema,
  FieldSchema,
  RelationSchema,
} from '@newel/core'
import { toSnakeCase, tableName, enumTypeName } from '@newel/core'

/** IR version this generator was written against. Any other version fails loudly. */
export const BUILT_AGAINST_IR_VERSION = '3.0.0'

export interface DrizzleGeneratorOptions {
  /** Prefix for module specifiers, e.g. `npm:` for Deno. Default: none. */
  importPrefix?: string
  /** Output directory (relative to the generators' output root). Default: `drizzle`. */
  outDir?: string
  /** Database column naming. `snake` (default) maps camelCase fields to snake_case columns. */
  casing?: 'snake' | 'camel'
}

function lcFirst(s: string): string {
  return s.charAt(0).toLowerCase() + s.slice(1)
}

function fileSlug(entityName: string): string {
  return toSnakeCase(entityName)
}

function str(s: string): string {
  return JSON.stringify(s)
}

class DrizzleEmitter {
  private readonly pgCore: string
  private readonly orm: string
  private readonly outDir: string
  private readonly casing: 'snake' | 'camel'

  constructor(
    private readonly schema: FabricSchema,
    opts: DrizzleGeneratorOptions,
  ) {
    const prefix = opts.importPrefix ?? ''
    this.pgCore = `${prefix}drizzle-orm/pg-core`
    this.orm = `${prefix}drizzle-orm`
    this.outDir = (opts.outDir ?? 'drizzle').replace(/\/+$/, '')
    this.casing = opts.casing ?? 'snake'
  }

  files(): GeneratorOutput['files'] {
    const header = '// @generated by @newel/generator-drizzle — do not edit\n'
    const out: GeneratorOutput['files'] = []
    const entities = Object.values(this.schema.entities)
    for (const e of entities) {
      out.push({
        path: `${this.outDir}/${fileSlug(e.name)}.ts`,
        content: this.entityFile(e),
        header,
      })
    }
    const barrel = entities.map((e) => `export * from './${fileSlug(e.name)}'`)
    out.push({
      path: `${this.outDir}/index.ts`,
      content: barrel.join('\n') + (barrel.length ? '\n' : 'export {}\n'),
      header,
    })
    return out
  }

  private col(name: string): string {
    return this.casing === 'snake' ? toSnakeCase(name) : name
  }

  private tbl(entityName: string): string {
    return this.casing === 'snake' ? tableName(entityName) : lcFirst(entityName)
  }

  private enumVar(entityName: string, field: FieldSchema): string {
    return `${lcFirst(entityName)}${field.name.charAt(0).toUpperCase()}${field.name.slice(1)}Enum`
  }

  private tableVar(entityName: string): string {
    return `${lcFirst(entityName)}Table`
  }

  private defaultExpr(field: FieldSchema): string {
    const v = field.defaultValue
    if (v === undefined) return ''
    if (field.type === 'bigint' || field.type === 'money') {
      const text = String(v)
      if (!/^-?\d+$/.test(text)) {
        throw new Error(
          `@newel/generator-drizzle: ${field.type} field "${field.name}" has non-integer defaultValue ${JSON.stringify(text)}`,
        )
      }
      return `.default(${text}n)`
    }
    if (field.type === 'timestamp' || field.type === 'date') return ''
    if (field.type === 'decimal' && typeof v === 'number')
      return `.default(${JSON.stringify(String(v))})`
    if (typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean') {
      return `.default(${JSON.stringify(v)})`
    }
    if (field.type === 'json') return `.default(${JSON.stringify(v)})`
    return ''
  }

  private column(entity: EntitySchema, field: FieldSchema, used: Set<string>): string {
    const c = str(this.col(field.name))
    let expr: string
    switch (field.type) {
      case 'uuid':
        expr = `uuid(${c})`
        used.add('uuid')
        break
      case 'integer':
        expr = `integer(${c})`
        used.add('integer')
        break
      case 'number':
        expr = `doublePrecision(${c})`
        used.add('doublePrecision')
        break
      case 'decimal':
        expr = `numeric(${c}, { precision: 19, scale: 4 })`
        used.add('numeric')
        break
      case 'bigint':
      case 'money':
        expr = `bigint(${c}, { mode: 'bigint' })`
        used.add('bigint')
        break
      case 'boolean':
        expr = `boolean(${c})`
        used.add('boolean')
        break
      case 'timestamp':
        expr = `timestamp(${c}, { withTimezone: true })`
        used.add('timestamp')
        break
      case 'date':
        expr = `date(${c})`
        used.add('date')
        break
      case 'json':
        expr = `jsonb(${c})`
        used.add('jsonb')
        break
      case 'enum':
        if (field.enumValues && field.enumValues.length > 0) {
          expr = `${this.enumVar(entity.name, field)}(${c})`
          break
        }
        expr = `text(${c})`
        used.add('text')
        break
      default:
        expr = `text(${c})`
        used.add('text')
    }
    if (field.primaryKey) {
      expr += '.primaryKey()'
      if (field.type === 'uuid') expr += '.defaultRandom()'
    } else if (!field.nullable) {
      expr += '.notNull()'
    }
    expr += this.defaultExpr(field)
    if (field.foreignKey) {
      const [refEntity, refField = 'id'] = field.foreignKey.split('.')
      if (this.schema.entities[refEntity]) {
        if (refEntity === entity.name) {
          // Self-reference: explicit return type breaks the circular type inference
          used.add('type AnyPgColumn')
          expr += `.references((): AnyPgColumn => ${this.tableVar(refEntity)}.${refField})`
        } else {
          expr += `.references(() => ${this.tableVar(refEntity)}.${refField})`
        }
      }
    }
    return expr
  }

  private entityFile(entity: EntitySchema): string {
    const used = new Set<string>(['pgTable'])
    const ormUsed = new Set<string>()
    const body: string[] = []

    // Enums
    for (const field of Object.values(entity.fields)) {
      if (field.type === 'enum' && field.enumValues && field.enumValues.length > 0) {
        used.add('pgEnum')
        const vals = field.enumValues.map(str).join(', ')
        body.push(
          `export const ${this.enumVar(entity.name, field)} = pgEnum(${str(enumTypeName(entity.name, field.name))}, [${vals}])`,
          '',
        )
      }
    }

    // Table
    const cols = Object.values(entity.fields).map(
      (f) => `  ${f.name}: ${this.column(entity, f, used)},`,
    )
    const checks: string[] = []
    for (const f of Object.values(entity.fields)) {
      if (f.pattern === undefined) continue
      used.add('check')
      ormUsed.add('sql')
      const lit = f.pattern
        .replace(/\\/g, '\\\\')
        .replace(/'/g, "''")
        .replace(/`/g, '\\`')
        .replace(/\$\{/g, '\\${')
      const cname = `chk_${tableName(entity.name)}_${toSnakeCase(f.name)}_pattern`
      checks.push(`    check(${str(cname)}, sql\`${'${table.' + f.name + '}'} ~ '${lit}'\`),`)
    }
    const tv = this.tableVar(entity.name)
    if (checks.length > 0) {
      body.push(
        `export const ${tv} = pgTable(${str(this.tbl(entity.name))}, {`,
        ...cols,
        '}, (table) => [',
        ...checks,
        '])',
        '',
      )
    } else {
      body.push(`export const ${tv} = pgTable(${str(this.tbl(entity.name))}, {`, ...cols, '})', '')
    }

    // Join tables for manyToMany owned by this entity
    for (const rel of Object.values(entity.relations)) {
      if (rel.kind !== 'manyToMany') continue
      // `through` naming an existing entity: that entity's own table is the join table
      if (rel.through && this.schema.entities[rel.through]) continue
      // Both sides declare the relation: only the alphabetically first owner emits it
      const inverse = this.schema.entities[rel.target]?.relations
      if (
        entity.name > rel.target &&
        inverse &&
        Object.values(inverse).some((r) => r.kind === 'manyToMany' && r.target === entity.name)
      ) {
        continue
      }
      used.add('uuid')
      used.add('primaryKey')
      const left = toSnakeCase(entity.name)
      const right = toSnakeCase(rel.target)
      const joinName = rel.through ? toSnakeCase(rel.through) : `${left}_${right}`
      const jv = `${lcFirst(rel.through ?? entity.name + rel.target)}JoinTable`
      body.push(
        `export const ${jv} = pgTable(${str(joinName)}, {`,
        `  ${lcFirst(entity.name)}Id: uuid(${str(left + '_id')}).notNull().references(() => ${tv}.id),`,
        `  ${lcFirst(rel.target)}Id: uuid(${str(right + '_id')}).notNull().references(() => ${this.tableVar(rel.target)}.id),`,
        '}, (table) => [',
        `  primaryKey({ columns: [table.${lcFirst(entity.name)}Id, table.${lcFirst(rel.target)}Id] }),`,
        '])',
        '',
      )
    }

    // Relations
    const relLines = this.relationLines(entity, tv)
    if (relLines.length > 0) {
      ormUsed.add('relations')
      body.push(
        `export const ${lcFirst(entity.name)}Relations = relations(${tv}, ({ one, many }) => ({`,
      )
      body.push(...relLines, '}))', '')
    }

    // Imports
    const imports: string[] = []
    imports.push(`import { ${[...used].sort().join(', ')} } from ${str(this.pgCore)}`)
    if (ormUsed.size > 0) {
      imports.push(`import { ${[...ormUsed].sort().join(', ')} } from ${str(this.orm)}`)
    }
    const refs = new Set<string>()
    const addRef = (name: string): void => {
      if (name !== entity.name && this.schema.entities[name]) refs.add(name)
    }
    for (const f of Object.values(entity.fields)) {
      if (f.foreignKey) addRef(f.foreignKey.split('.')[0])
    }
    for (const r of Object.values(entity.relations)) addRef(r.target)
    for (const r of [...refs].sort()) {
      imports.push(`import { ${this.tableVar(r)} } from './${fileSlug(r)}'`)
    }

    return [...imports, '', ...body].join('\n').replace(/\n+$/, '\n')
  }

  private relationLines(entity: EntitySchema, tv: string): string[] {
    const lines: string[] = []
    for (const rel of Object.values(entity.relations)) {
      const targetVar = this.tableVar(rel.target)
      if (!this.schema.entities[rel.target]) continue
      lines.push(...this.oneRelation(entity, tv, rel, targetVar))
    }
    return lines
  }

  private oneRelation(
    entity: EntitySchema,
    tv: string,
    rel: RelationSchema,
    targetVar: string,
  ): string[] {
    switch (rel.kind) {
      case 'belongsTo': {
        const fk = rel.foreignKey ?? `${lcFirst(rel.target)}Id`
        if (!(fk in entity.fields)) return [`  ${rel.name}: one(${targetVar}),`]
        return [
          `  ${rel.name}: one(${targetVar}, { fields: [${tv}.${fk}], references: [${targetVar}.id] }),`,
        ]
      }
      case 'hasOne':
      case 'hasMany': {
        // Drizzle infers the join from the target's belongsTo; without one the relation is unusable
        const target = this.schema.entities[rel.target]
        // Several belongsTo to the same entity make the inference ambiguous (Drizzle throws), so skip
        const inverses = Object.values(target.relations).filter(
          (r) => r.kind === 'belongsTo' && r.target === entity.name,
        )
        if (inverses.length !== 1) return []
        return [`  ${rel.name}: ${rel.kind === 'hasOne' ? 'one' : 'many'}(${targetVar}),`]
      }
      default:
        return []
    }
  }
}

export class DrizzleGenerator implements Generator {
  readonly name = 'drizzle'
  readonly dependsOn: string[] = []

  constructor(private readonly options: DrizzleGeneratorOptions = {}) {}

  async generate(schema: FabricSchema, _ctx: GeneratorContext): Promise<GeneratorOutput> {
    if (schema.version !== BUILT_AGAINST_IR_VERSION) {
      throw new Error(
        `@newel/generator-drizzle was built against IR ${BUILT_AGAINST_IR_VERSION} but received IR ${schema.version}; update the generator before regenerating`,
      )
    }
    return { files: new DrizzleEmitter(schema, this.options).files() }
  }
}
